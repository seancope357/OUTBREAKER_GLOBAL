const COUNTRY_KEYS_BY_LENGTH = Object.keys(COUNTRY_CENTROIDS).sort((a, b) => b.length - a.length);

// Find the first country mentioned in `text` (longest-name-first to avoid "Korea" stealing "South Korea").
export function findCountryInText(text: string): GeoPoint | null {
  if (!text) return null;
  const haystack = ' ' + text.toLowerCase() + ' ';
  for (const key of COUNTRY_KEYS_BY_LENGTH) {
    // Word-boundary match — avoid "indiana" matching "india".
    const needle = ` ${key} `;
    if (haystack.includes(needle)) return COUNTRY_CENTROIDS[key];
    if (haystack.includes(` ${key},`) || haystack.includes(` ${key}.`) || haystack.includes(`(${key})`)) {
      return COUNTRY_CENTROIDS[key];
    }
  }
  return null;
}

export function lookupUsJurisdiction(name: string | undefined | null): GeoPoint | null {
  if (!name) return null;
  return US_JURISDICTION_CENTROIDS[name.trim().toLowerCase()] || null;
}
